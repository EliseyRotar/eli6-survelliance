def scan_port(args):
    host, ip, port = args
    try:
        s = socket.create_connection((ip, port), timeout=1.5)
        try:
            banner = s.recv(256)
        except:
            banner = b''
        s.close()
        return (host, ip, port, banner[:50])
    except Exception:
        return None


